  itemsSummary: string;
  /** 商品明细 */
  itemsDetail: string[];
  /** 总件数 */
  totalQty: number;
  /** 总重量 */
  totalWeight: string;
  /** 出库类型: 销售出库 / 调拨出库 / 退供出库 */
  outboundType: string;
  /** 出库状态: 待出库 / 出库中 / 已出库 / 已取消 / 取消中 */
